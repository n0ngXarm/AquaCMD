THEMES = {'light': LIGHT, 'dark': DARK}
DEFAULT_THEME = 'light'


def gtk_definitions(mode):
    """Map web hyphenated names to GTK symbolic-color identifiers."""
    return '\n'.join('@define-color '+key.replace('-', '_')+' '+value+';'
                     for key, value in THEMES[mode].items()
                     if re.fullmatch(r'#[0-9a-fA-F]{3,8}|rgba?\([^()]*\)', value)) + '\n'


def compile_native_css(mode, source):
    """Scalar templates complement GTK's symbolic colours, without generated files."""
    if isinstance(source, bytes):
        source = source.decode('utf-8')
    def value(match):
        return THEMES[mode][match[1]]
    return (gtk_definitions(mode) + re.sub(r'\{\{([\w-]+)\}\}', value, source)).encode()
